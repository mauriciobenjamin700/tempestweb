/**
 * Bundle the Mode A client into one module, at release time.
 *
 * `client/` stays build-free: every module is plain ESM that the node tests,
 * Mode B and Mode C load as written. Only the wasm artifact pays for loading it
 * as a tree, because its static imports form a waterfall the browser has to walk
 * before the bootstrap can even ask for Pyodide (81 requests, ~2.9 s on a
 * throttled phone). So the wasm surface (`client/wasm-entry.js`) is bundled here
 * with esbuild and the result is committed under `client/bundle/`, where the
 * wheel's force-include picks it up with the rest of `client/`.
 *
 * esbuild is a pinned npm devDependency and never a dependency of the Python
 * package: `tempestweb build` only copies the committed file. Next to the bundle
 * goes `tempestweb-wasm.json`, the SHA-256 of every input module, which
 * `tests/unit/test_client_bundle.py` re-hashes so a client edit without a
 * re-bundle fails the suite instead of shipping stale code.
 *
 * Usage:
 *   node scripts/bundle-client.mjs           write the bundle + its manifest
 *   node scripts/bundle-client.mjs --check   exit 1 if the committed copy drifted
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build, version as esbuildVersion } from "esbuild";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CLIENT = join(ROOT, "client");
const ENTRY = join(CLIENT, "wasm-entry.js");
const OUT_DIR = join(CLIENT, "bundle");
const BUNDLE = join(OUT_DIR, "tempestweb-wasm.js");
const MANIFEST = join(OUT_DIR, "tempestweb-wasm.json");

/**
 * SHA-256 of a byte string, hex encoded.
 *
 * @param {Uint8Array | string} data  The bytes to hash.
 * @returns {string} The hex digest.
 */
function sha256(data) {
  return createHash("sha256").update(data).digest("hex");
}

/**
 * Run esbuild over the wasm entry and describe what it read.
 *
 * Minified because the bundle is a delivery artifact, not a source: the readable
 * modules ship beside it in the wheel. `keepNames` keeps function and class
 * names intact, so a stack trace from a phone still says `CapabilityError` or
 * `applyPatches` instead of a two-letter alias. The banner names the generator so
 * nobody edits the output by hand.
 *
 * @returns {Promise<{code: string, manifest: object}>} The bundle text and the
 *   manifest (input hashes, esbuild version, bundle hash) to write next to it.
 */
async function bundle() {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    format: "esm",
    target: "es2022",
    minify: true,
    keepNames: true,
    legalComments: "none",
    charset: "utf8",
    write: false,
    metafile: true,
    logLevel: "warning",
    banner: { js: "// GENERATED by scripts/bundle-client.mjs from client/wasm-entry.js — do not edit." },
  });
  const code = result.outputFiles[0].text;
  const inputs = {};
  for (const path of Object.keys(result.metafile.inputs).sort()) {
    const absolute = resolve(ROOT, path);
    inputs[relative(CLIENT, absolute).split("\\").join("/")] = sha256(readFileSync(absolute));
  }
  const manifest = {
    entry: "wasm-entry.js",
    esbuild: esbuildVersion,
    bundle_sha256: sha256(code),
    inputs,
  };
  return { code, manifest };
}

const { code, manifest } = await bundle();
const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;

if (process.argv.includes("--check")) {
  let committed = "";
  try {
    committed = readFileSync(BUNDLE, "utf8");
  } catch {
    committed = "";
  }
  if (committed !== code) {
    console.error("client/bundle/tempestweb-wasm.js is stale: run `npm run bundle`.");
    process.exit(1);
  }
  console.log(`bundle up to date (${code.length} bytes, ${Object.keys(manifest.inputs).length} modules)`);
} else {
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(BUNDLE, code);
  writeFileSync(MANIFEST, manifestText);
  console.log(`wrote ${relative(ROOT, BUNDLE)} (${code.length} bytes, ${Object.keys(manifest.inputs).length} modules)`);
}
